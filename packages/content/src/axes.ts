/*
 * 同一章入面正反兩面（2026-10-18 · 後生讀者抽樣 B9）。
 *
 * 細讀係原書帶條件嘅講法（「同宮有鈴星，在外多挫折不安」），結論、結構講一般情況（「出門在外大多是有福的」）。
 * 兩句都啱，但擺埋一齊冇講明邊句係例外，讀者見到嘅就係自相矛盾。逐宮列出講緊同一件事嘅兩極，
 * assemble.ts `bridgeExceptions` 用嚟：
 *   一、細讀入面「一般⋯」嗰條撞到相反方向嘅帶條件規則：剷「一般」嗰條（書本身就係一般如此、見某星例外）；
 *   二、細讀句同前面結論／結構方向相反：句首加「不過，」講明係例外。
 * 字表寧願窄：認錯一句兩極，會喺唔矛盾嘅地方加「不過」。
 */
type Axis = { neg: RegExp; pos: RegExp };
export const AXES: Record<string, Axis> = {
  遷移: { neg: /在外多(挫折|是非)|功虧一簣/, pos: /得福|有福|順心|提攜|受人敬重|在外機會多|得利/ },
  田宅: { neg: /家宅不(安|寧)|不得安寧|搬動得多|住處常在變/, pos: /寧靜|住得安穩|聚居一處|不輕易搬|不容易輕率搬動|安頓下來阻力比較小/ },
  父母: { neg: /不和|緣[份分]較淺|疏遠|隔膜|隔閡|摩擦|關係較差|意見不合|各有成見/, pos: /寵愛|融洽|和美|和睦|順遂|關係一般良好|關係也好/ },
  兄弟: { neg: /不和|爭執|爭權|心計|合不來/, pos: /和睦|和好|和美|融洽|合得來|和氣/ },
  子女: { neg: /代溝|隔閡|不和|意見不合|先好後壞|不長久|顧忌|(?<!有)隔膜/, pos: /融洽|深厚|和美|投契|和洽|和好/ },
  夫妻: { neg: /不和|爭論|磨擦|摩擦/, pos: /和美|和睦|融洽|合拍/ },
  命宮: { neg: /起步(偏|較|比較)晚|晚發/, pos: /起步比別人省力|早發/ },
};

const NEGATED = (pos: RegExp) => new RegExp(`(?:不易|不夠|不|難以|難|未必)(?:${pos.source})`);

/** -1 負、1 正、0 冇講或者兩面都講 */
export function poleOf(palace: string, sentence: string): -1 | 0 | 1 {
  const a = AXES[palace];
  if (!a) return 0;
  /* 「表面融洽，心裡卻⋯」兩面都講 */
  if (sentence.includes('表面')) return 0;
  const n = a.neg.test(sentence) || NEGATED(a.pos).test(sentence);
  /* 「不易和睦」「難以融洽」唔算正面 */
  const p = new RegExp(`(?<!不易|不夠|不|難以|難|未必)(?:${a.pos.source})`).test(sentence);
  return n === p ? 0 : n ? -1 : 1;
}
