function lookPart(zh: string, missing: string[]): string {
  let m = /^你走進第(\S+?)個大限，(正是開頭說的關鍵大限，)?生活的重心換了方向，(.+)$/.exec(zh);
  if (m && n(m[1]!) && TURN_EG[m[3]!]) {
    const key = m[2] ? '（冒頭で挙げた大切な大限です）' : '';
    return `${kanjiNum(n(m[1]!)!)}番目の大限${key}に入り、暮らしの重心の向きが変わりました。${TURN_EG[m[3]!]}です`;
  }
  if (EVENT_JA[zh]) return EVENT_JA[zh]!;
  m = /^同一年，(.+)$/.exec(zh);
  if (m && GIST_JA[m[1]!]) return `同じ年、${GIST_JA[m[1]!]}`;
  if (m) {
    const j = m[1]!.indexOf('，像是');
    const g = m[1]!.slice(0, j);
    const e = m[1]!.slice(j + 1);
    if (j > 0 && GIST_JA[g] && GIST_JA[e]) return `同じ年、${GIST_JA[g]}。${GIST_JA[e]}です`;
  }
  if (GIST_JA[zh]) return GIST_JA[zh]!;
  const i = zh.indexOf('，像是');
  if (i > 0 && GIST_JA[zh.slice(0, i)] && GIST_JA[zh.slice(i + 1)]) return `${GIST_JA[zh.slice(0, i)]}。${GIST_JA[zh.slice(i + 1)]}です`;
  missing.push(zh);
  return `〔${zh}〕`;
}

