/**
 * 簡體：命盤詞彙逐字對照（2026-10-08）
 *
 * client 元件（命盤、落款）自己由資料砌中文：星名、宮名、廟旺、四化、干支、出生地。
 * 呢啲詞彙係有限嘅，逐字換就夠，唔使將成個 OpenCC 送去瀏覽器。
 * 其餘所有字（介面、正文、藏經閣）喺 server 轉（`hans.ts`）。
 *
 * ⚠ 呢張表係由 OpenCC（tw → cn）對住全部命盤詞彙生出嚟嘅；
 *   `test/hans.test.ts` 隨機排盤再對一次 —— 加新星或者新地點，漏咗字就會爆。
 */
export const HANS_ZI: Readonly<Record<string, string>> = {
  祿: '禄', 權: '权', 廟: '庙', 廣: '广', 倫: '伦', 紐: '纽', 約: '约', 宮: '宫', 門: '门', 輔: '辅',
  殺: '杀', 陽: '阳', 僕: '仆', 羅: '罗', 遷: '迁', 機: '机', 軍: '军', 財: '财', 鉞: '钺', 陰: '阴',
  鈴: '铃', 貞: '贞', 貪: '贪', 馬: '马',
};

/** `on`（簡體頁）就逐字換。 */
export function zi(s: string, on: boolean): string {
  return on ? [...s].map((c) => HANS_ZI[c] ?? c).join('') : s;
}
